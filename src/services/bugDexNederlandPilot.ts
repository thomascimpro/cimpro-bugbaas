function nederlandPilotRarity(id: string): BugDexRarity {
  if (legendaryNederlandPilotIds.has(id)) return "Legendarisch";
  if (epicNederlandPilotIds.has(id)) return "Episch";
  if (rareNederlandPilotIds.has(id)) return "Zeldzaam";
  return "Gewoon";
}

export const bugDexNederlandPilotEntries: BugDexEntry[] = bugDexNederlandPilotDefinitions.map((definition) => {
  const rarity = nederlandPilotRarity(definition.id);
  return {
    id: definition.id,
    name: definition.name,
    title: rarity === "Gewoon" ? "Nederlandse soortkaart" : `${rarity} Nederlandse soortkaart`,
    minPoints: 0,
    minBugs: 0,
    rarity,
    insect: definition.insect,
    evolutionLevel: rarity === "Legendarisch" ? 6 : rarity === "Episch" ? 5 : rarity === "Zeldzaam" ? 4 : 3,
    note: `${definition.name} (${definition.scientificName}) — ${definition.contexts.join(", ")}.`,
    unlockMode: "drop",
  };
});

export const bugDexNederlandPilotFacts: Record<string, string> = Object.fromEntries(
  bugDexNederlandPilotDefinitions.map((definition) => [definition.id, definition.fact])
);
